"""Render the current Zellij keybindings from the checked-in KDL subset.

This reads data only. It deliberately supports the keybind/mode/bind/action
structure used by our config, not arbitrary KDL expressions.
"""

from pathlib import Path
import re
import shlex

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".config/zellij/config.kdl"

BIND = re.compile(r'^\s*bind\s+"([^"]+)"\s*\{\s*$')
MODE = re.compile(r"^\s*([a-z]+)\s*\{\s*$")
NOTE = re.compile(r"^\s*// doc: (binding|note) ([^|]+)\| (.+)$")
SETTING = re.compile(r'^(default_mode|theme|default_layout|scroll_buffer_size|pane_frames|pane_frame_style)\s+(.+)$')


def braces(line: str) -> int:
    """Count KDL block delimiters outside quoted strings and comments."""
    quoted = escaped = False
    count = 0
    for i, ch in enumerate(line):
        if not quoted and line[i:i + 2] == "//":
            break
        if quoted and escaped:
            escaped = False
        elif quoted and ch == "\\":
            escaped = True
        elif ch == '"':
            quoted = not quoted
        elif not quoted:
            count += (ch == "{") - (ch == "}")
    if quoted:
        raise ValueError("Unclosed KDL string")
    return count


def summarize(actions: list[str]) -> str:
    """Describe the first action; trailing mode resets are control flow."""
    primary = next((a for a in actions if not a.startswith("SwitchToMode ")), actions[0])
    tokens = shlex.split(primary.removesuffix(" {").strip())
    name, *args = tokens
    if name == "Run":
        command = " ".join(args)
        match = re.search(r"bin/([,a-zA-Z0-9_-]+)", command)
        return f"Run {match.group(1)}" if match else f"Run {command}"
    if name == "MessagePlugin":
        payload = next((shlex.split(action)[1] for action in actions if action.strip().startswith("payload ")), None)
        return f"Vim/Zellij navigator ({payload})" if payload else "Send plugin message"
    if name == "SwitchToMode":
        return f"Switch to {args[0]} mode" if args else "Switch mode"
    if name == "GoToTab":
        return f"Go to tab {args[0]}"
    if name == "Resize":
        return f"Resize {args[0].lower()}" if args else "Resize"
    if name == "NewPane":
        return f"New pane {args[0].lower()}" if args else "New pane"
    if name == "Search":
        return f"Search {args[0]}" if args else "Search"
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name).capitalize()


def render(source: Path = SOURCE) -> str:
    depth = 0
    mode = None
    binding = None
    actions: list[str] = []
    bindings: list[tuple[str, str, str]] = []
    descriptions: dict[str, str] = {}
    notes: list[str] = []
    settings: dict[str, str] = {}
    for raw in source.read_text().splitlines():
        line = raw.strip()
        annotation = NOTE.fullmatch(raw)
        if annotation:
            kind, key, description = annotation.groups()
            if kind == "note":
                notes.append(description)
            else:
                key = key.strip()
                if key in descriptions:
                    raise ValueError(f"Duplicate Zellij binding annotation: {key}")
                descriptions[key] = description.strip()
            continue
        if depth == 0:
            setting = SETTING.fullmatch(line)
            if setting:
                settings[setting.group(1)] = setting.group(2).strip('"')
        if depth == 1:
            candidate = MODE.fullmatch(raw)
            if candidate:
                mode = candidate.group(1)
        if depth == 2:
            candidate = BIND.fullmatch(raw)
            if candidate:
                binding = candidate.group(1)
                actions = []
        elif depth >= 3 and binding is not None and line and not line.startswith(("}", "//")):
            actions.append(line)

        depth += braces(raw)
        if depth < 0:
            raise ValueError("Unmatched closing brace in Zellij config")
        if binding is not None and depth == 2:
            if not actions:
                raise ValueError(f"Empty bind {mode}:{binding}")
            bindings.append((mode or "", binding, summarize(actions)))
            binding = None
        if depth == 1:
            mode = None
    if depth != 0:
        raise ValueError("Unclosed KDL block")
    if not bindings:
        raise ValueError("No Zellij bindings found")

    used = set()
    lines = [
        "# Zellij",
        "",
        "<!-- Generated by scripts/docs/generate.py. Do not edit. -->",
        "",
        "Starts in the \`locked\` mode. Use \`Ctrl+A\` to enter \`normal\` mode.",
        "From \`normal\`, press \`Y\` to enter the \`move\` (yank) mode.",
        "",
        "## Keybindings",
        "",
        "| Mode | Key | Action |",
        "| --- | --- | --- |",
    ]
    for mode, key, action in bindings:
        description_key = f"{mode}:{key}"
        if description_key in descriptions:
            action = descriptions[description_key]
            used.add(description_key)
        lines.append(f"| \`{mode}\` | \`{key}\` | {action} |")
    leftovers = descriptions.keys() - used
    if leftovers:
        raise ValueError(f"Annotations without matching Zellij bindings: {sorted(leftovers)}")

    if settings:
        lines += ["", "## Settings", "", "| Setting | Value |", "| --- | --- |"]
        for name, value in settings.items():
            lines.append(f"| \`{name}\` | \`{value}\` |")
    if notes:
        lines += ["", "## Notes", ""]
        lines.extend(f"- {description}" for description in notes)
    return "\n".join(lines) + "\n"
