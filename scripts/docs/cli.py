"""Generate a CLI reference from audited, side-effect-free --help routes."""

from pathlib import Path
import os
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]

# Deliberate allowlist. Each entry must exit before doing setup, I/O or networking.
COMMANDS = (
    ("Initial setup", "get-started.sh"),
    ("Machine bootstrap", "scripts/setup/bootstrap.sh"),
    ("Update checkout", "scripts/setup/update.sh"),
    ("Cleanup", "scripts/setup/cleanup.sh"),
    ("Install prompt", "scripts/setup/setup-prompt.sh"),
    ("Set up Podman", "scripts/setup/setup-podman.sh"),
    ("Private overlay", "scripts/setup/apply-private-overlay.sh"),
    ("Format shell scripts", "scripts/dev/format.sh"),
    ("Lint shell scripts", "scripts/dev/lint.sh"),
    ("Install Git hooks", "scripts/dev/install-hooks.sh"),
    ("OpenCode sandbox", "bin/opencode-sandbox"),
)


def help_text(root: Path, path: str) -> str:
    script = root / path
    if not script.is_file() or script.is_symlink():
        raise ValueError(f"Missing or symlinked help source: {path}")
    with tempfile.TemporaryDirectory(prefix="dotfiles-help-") as scratch:
        # No credentials, user config, TTY, project environment, or installed tools.
        # Only approved scripts are invoked and they must exit early on --help.
        environment = {
            "HOME": scratch,
            "TMPDIR": scratch,
            "PATH": os.defpath,
            "LANG": "C",
        }
        try:
            result = subprocess.run(
                ["bash", str(script), "--help"],
                cwd=root,
                env=environment,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=5,
                check=False,
            )
        except subprocess.TimeoutExpired as exc:
            raise ValueError(f"Timed out collecting --help from {path}") from exc
        if list(Path(scratch).iterdir()):
            raise ValueError(f"--help wrote into its temporary HOME: {path}")
    output = result.stdout.strip()
    if result.returncode != 0 or not output.startswith("Usage:") or result.stderr:
        raise ValueError(
            f"Unexpected --help result from {path}: exit={result.returncode}, "
            f"stdout={output!r}, stderr={result.stderr.strip()!r}"
        )
    return output


def render(root: Path = ROOT) -> str:
    lines = [
        "# Command reference",
        "",
        "<!-- Generated by scripts/docs/generate.py. Do not edit. -->",
        "",
        "Run commands from the dotfiles checkout unless noted otherwise.",
        "This reference is generated from each script's `--help` output.",
    ]
    for title, path in COMMANDS:
        lines += [
            "",
            f"## {title}",
            "",
            f"Source: [`{path}`](../../{path})",
            "",
            "```text",
            help_text(root, path),
            "```",
        ]
    return "\n".join(lines) + "\n"
