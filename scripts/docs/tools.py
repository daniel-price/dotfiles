"""Render declared tools and packages directly from mise TOML manifests."""

from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[2]


def markdown(value: object) -> str:
    return str(value).replace("|", r"\|").replace("\n", " ")


def render(machine: Path = ROOT / ".config/mise/base-tools.toml",
           development: Path = ROOT / "mise.toml",
           bootstrap: Path = ROOT / "scripts/setup/mise.toml") -> str:
    manifests = [
        ("Machine tools", machine),
        ("Repository development tools", development),
    ]
    lines = [
        "# Tool inventory",
        "",
        "<!-- Generated by scripts/docs/generate.py. Do not edit. -->",
        "",
        "This lists declared versions, not what is installed on this computer.",
        "Machine tools are provisioned by bootstrap; development tools are local to this checkout.",
    ]
    for heading, path in manifests:
        config = tomllib.loads(path.read_text())
        tools = config.get("tools", {})
        if not tools:
            raise ValueError(f"No tools defined in {path}")
        lines += ["", f"## {heading}", "", "| Tool | Pinned version |", "| --- | --- |"]
        for name, version in tools.items():
            if not isinstance(version, str):
                raise ValueError(f"Unsupported mise version declaration: {name} in {path}")
            lines.append(f"| `{markdown(name)}` | `{markdown(version)}` |")
        if heading == "Machine tools":
            packages = tomllib.loads(bootstrap.read_text()).get("bootstrap", {}).get("packages", {})
            if packages:
                lines += ["", "### Platform packages", "", "| Package | Platform |", "| --- | --- |"]
                for name, details in packages.items():
                    if not isinstance(details, dict) or not isinstance(details.get("os"), str):
                        raise ValueError(f"Unsupported platform package: {name}")
                    lines.append(f"| `{markdown(name)}` | `{markdown(details['os'])}` |")
    return "\n".join(lines) + "\n"
