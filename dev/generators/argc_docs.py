"""Generate Markdown CLI references from argc's structured export, not Bash comments."""

import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
# Each source is reviewed: argc --argc-export reads annotations, not executable code.
SOURCES = ("bin/,uuid",)


def cell(value: object) -> str:
    return str(value).replace("|", r"\|").replace("\n", "<br>")


def default(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, dict):
        if value.get("type") == "Value":
            return cell(value.get("value", ""))
        if value.get("type") == "Fn":
            return "dynamic (" + cell(value.get("value", "")) + ")"
    return cell(value)


def choices(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, dict):
        data = value.get("data", [])
        if value.get("type") == "Values":
            return ", ".join(cell(item) for item in data) or "—"
        if value.get("type") == "Fn":
            return "dynamic (" + cell(data[0] if data else "") + ")"
    return cell(value)


def table(lines: list[str], headings: list[str], rows: list[tuple[str, ...]]) -> None:
    if not rows:
        return
    lines.extend([
        "| " + " | ".join(headings) + " |",
        "| " + " | ".join("---" for _ in headings) + " |",
    ])
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    lines.append("")


def sections(command: dict, prefix: str = "", level: int = 1) -> list[str]:
    name = command["name"]
    full_name = (prefix + " " + name).strip()
    lines = ["#" * min(level, 6) + " `" + cell(full_name) + "`", ""]
    description = command.get("describe")
    if description:
        lines.extend([str(description).strip(), ""])

    options = []
    for option in command.get("flag_options", []):
        spellings = option.get("names") or [
            option[key] for key in ("short_name", "long_name") if option.get(key)
        ]
        spelling = ", ".join(spellings)
        if not option.get("flag") and option.get("notations"):
            spelling += " " + " ".join("<" + item + ">" for item in option["notations"])
        options.append((
            "`" + cell(spelling) + "`",
            cell(option.get("describe", "")),
            "yes" if option.get("required") else "no",
            default(option.get("default")),
            choices(option.get("choice")),
        ))
    if options:
        lines.extend(["#" * min(level + 1, 6) + " Options", ""])
        table(lines, ["Flag / option", "Description", "Required", "Default", "Choices"], options)

    arguments = []
    for arg in command.get("positionals", []):
        notation = arg.get("notation") or arg.get("id", "")
        if arg.get("multiple"):
            notation += "..."
        arguments.append((
            "`" + cell(notation) + "`",
            cell(arg.get("describe", "")),
            "yes" if arg.get("required") else "no",
            default(arg.get("default")),
            choices(arg.get("choice")),
        ))
    if arguments:
        lines.extend(["#" * min(level + 1, 6) + " Arguments", ""])
        table(lines, ["Argument", "Description", "Required", "Default", "Choices"], arguments)

    subcommands = command.get("subcommands", [])
    if subcommands:
        lines.extend(["#" * min(level + 1, 6) + " Subcommands", ""])
        table(lines, ["Command", "Description"], [
            ("`" + cell(sub["name"]) + "`", cell(sub.get("describe", "")))
            for sub in subcommands
        ])
        for sub in subcommands:
            lines.extend(sections(sub, full_name, level + 1))
    return lines


def render_export(payload: object, level: int = 1) -> str:
    if not isinstance(payload, dict) or not isinstance(payload.get("name"), str):
        raise ValueError("argc export must be a command object with a name")
    return "\n".join(sections(payload, level=level)).rstrip() + "\n"


def render(root: Path = ROOT) -> str:
    output = [
        "# Argc-powered commands",
        "",
        "<!-- Generated by dev/generators/generate.py. Do not edit. -->",
        "",
        "These commands use [argc](https://github.com/sigoden/argc) annotations for",
        "help, validation and Zsh completion; this reference comes from argc's JSON export.",
        "",
    ]
    for path in SOURCES:
        script = root / path
        if not script.is_file() or script.is_symlink():
            raise ValueError(f"Missing or symlinked argc script: {path}")
        try:
            result = subprocess.run(
                ["argc", "--argc-export", str(script)],
                cwd=root,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=10,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise ValueError(f"Cannot export argc metadata for {path}: {exc}") from exc
        if result.returncode:
            raise ValueError(f"argc export failed for {path}: {result.stderr.strip()}")
        try:
            definition = json.loads(result.stdout)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Invalid argc export for {path}: {exc}") from exc
        output.extend([f"Source: [`{path}`](../../{path})", "", render_export(definition, level=2)])
    return "\n".join(output).rstrip() + "\n"
