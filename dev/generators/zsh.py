#!/usr/bin/env python3
"""Generate the Zsh reference from its configuration without executing shell code."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
ZSH = ROOT / ".config" / "zsh"
ANNOTATION = re.compile(r"^# doc: (option|prompt|alias) ([^|]+)\| (.+)$")
ALIAS = re.compile(r"^\s*alias\s+([^=\s]+)='([^']*)'\s*$")


def render() -> str:
    comments: dict[tuple[str, str], str] = {}
    for filename in ("zshrc", "aliases.zsh"):
        for line in (ZSH / filename).read_text().splitlines():
            match = ANNOTATION.fullmatch(line)
            if match:
                category, name, description = match.groups()
                key = (category, name.strip())
                if key in comments:
                    raise ValueError(f"Duplicate documentation annotation: {key}")
                comments[key] = description.strip()

    zshrc = (ZSH / "zshrc").read_text()
    aliases = []
    for line in (ZSH / "aliases.zsh").read_text().splitlines():
        match = ALIAS.fullmatch(line)
        if match:
            name, expansion = match.groups()
            note = comments.pop(("alias", name), "")
            aliases.append((name, expansion, note))

    options = []
    for (category, name), description in list(comments.items()):
        if category == "option":
            if not re.search(r"^\s*setopt\s+" + re.escape(name) + r"(?:\s|$)", zshrc, re.M):
                raise ValueError(f"Documented option is not enabled: {name}")
            options.append((name, description))
            del comments[(category, name)]

    prompts = []
    for (category, name), description in list(comments.items()):
        if category == "prompt":
            prompts.append(description)
            del comments[(category, name)]
    if comments:
        raise ValueError(f"Unmatched documentation annotations: {comments}")

    if not aliases:
        raise ValueError("No Zsh aliases found; refusing to generate an empty reference")

    lines = [
        "# Zsh",
        "",
        "<!-- Generated by dev/generators/generate.py. Do not edit. -->",
        "",
        "## Aliases",
        "",
        "| Alias | Expands to | Notes |",
        "| --- | --- | --- |",
    ]
    for name, expansion, note in aliases:
        lines.append(f"| `{name}` | `{expansion}` | {note} |")

    if options:
        lines += ["", "## Shell options", ""]
        for name, description in options:
            lines += [f"### `{name}`", "", description, ""]
        if lines[-1] == "":
            lines.pop()

    if prompts:
        lines += ["", "## Prompt", ""]
        lines += [f"- {description}" for description in prompts]

    return "\n".join(lines) + "\n"

